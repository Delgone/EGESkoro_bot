# Гарантируем минимум 365 фраз зацикливанием базового набора
_BASE_LEN = len(PHRASES)
while len(PHRASES) < 365:
    PHRASES.append(PHRASES[len(PHRASES) % _BASE_LEN])


def get_phrase(index: int) -> tuple[str, int]:
    """Возвращает фразу и следующий индекс."""
    phrase = PHRASES[index % len(PHRASES)]
    next_index = (index + 1) % len(PHRASES)
    return phrase, next_index


def _days_word(n: int) -> str:
    """Склонение слова «день» под число."""
    if 11 <= n % 100 <= 19:
        return "дней"
    rem = n % 10
    if rem == 1:
        return "день"
    if 2 <= rem <= 4:
        return "дня"
    return "дней"


def build_progress_bar(percent: float) -> str:
    """Возвращает строку ▓▓▓░░░ на основе процента (0.0 - 1.0)"""
    total = 10
    filled = int(round(percent * total))
    filled = max(0, min(total, filled))
    return "▓" * filled + "░" * (total - filled)


def build_daily_message(user, active_subjects: list) -> str:
    """Собирает полное ежедневное сообщение."""
    now_utc = datetime.utcnow()

    # Проверка режима отдыха
    if user.rest_until and now_utc < user.rest_until:
        return (
            "🛌 <b>Режим отдыха активирован.</b>\n\n"
            "Забудь про таймеры и отсчеты. Твой мозг учится, даже когда ты отдыхаешь. "
            "Сон и восстановление — сейчас твои главные задачи. Набирайся сил!"
        )

    phrase, _ = get_phrase(user.phrase_index)
    days_since = (now_utc.date() - user.created_at.date()).days + 1

    lines = [
        f"День {days_since}",
    ]

    if user.streak_count > 0:
        lines.append(f"🔥 Серия подготовки: <b>{user.streak_count} дней</b>")

    lines.extend([
        "",
        f"<i>«{phrase}»</i>",
        "",
        "📊 <b>Твой прогресс:</b>"
    ])

    sorted_subjects = sorted(
        [s for s in active_subjects if not s.is_passed and s.exam_date],
        key=lambda s: s.exam_date,
    )

    for subj in sorted_subjects:
        days_left = subj.days_left
        if days_left is None:
            continue

        dw = _days_word(days_left)

        # Расчет визуального прогресса
        total_days = (subj.exam_date.date() - user.created_at.date()).days
        if total_days > 0:
            passed_days = (now_utc.date() - user.created_at.date()).days
            percent = max(0.0, min(1.0, passed_days / total_days))
            progress_bar = build_progress_bar(percent)
            percent_str = f"{int(percent * 100)}%"
        else:
            progress_bar = build_progress_bar(0)
            percent_str = "0%"

        lines.append(f"• {subj.subject_name}: {days_left} {dw}\n  {progress_bar} {percent_str}")

    lines += ["", "Держишься — и это уже победа. 💪"]
    return "\n".join(lines)


